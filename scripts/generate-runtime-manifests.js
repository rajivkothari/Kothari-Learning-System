#!/usr/bin/env node
// Writes the slim runtime manifests the app bundles, from the full manifests (the single source of
// truth for provenance, licensing, prompts, processing and validation):
//   content/themes/elevator-quest/art/manifest.json + rights.json -> content/themes/elevator-quest/art/runtime.json
//   assets/themes/elevator-quest/audio/manifest.json               -> assets/themes/elevator-quest/audio/runtime.json
// A runtime manifest keeps only what the game reads while it runs: for art, every entry as the schema
// parses it (state defaults to "any"; the short provenance stays, it costs under 1 KB of bytecode) and of
// each rights record only its approval and review flag; for sound, each pack's status and each file's
// pack, length and narration key. Never edit a runtime manifest by hand: change the full
// manifest and run this script (`node scripts/generate-runtime-manifests.js`). The art and audio
// tests fail while a runtime manifest is stale; `--check` exits 1 instead of writing.
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const ART_DIR = path.join(ROOT, 'content/themes/elevator-quest/art');
const AUDIO_DIR = path.join(ROOT, 'assets/themes/elevator-quest/audio');
const NOTE = 'Generated by scripts/generate-runtime-manifests.js from the full manifest beside it. Do not edit.';

/** Art: the entries as the schema parses them (state defaults to "any"), and each record's approval. */
function artRuntime(manifest, rights) {
  return {
    note: NOTE,
    manifest: { assets: manifest.assets.map((a) => ({ ...a, state: a.state ?? 'any' })) },
    rights: { assets: rights.assets.map((r) => ({ asset: r.asset, approval: r.approval, humanReviewed: r.humanReviewed })) },
  };
}

/** Sound: pack statuses, and per file its pack, length and narration key. */
function audioRuntime(manifest) {
  return {
    note: NOTE,
    packs: Object.fromEntries(Object.entries(manifest.packs).map(([id, p]) => [id, { status: p.status }])),
    assets: Object.fromEntries(Object.entries(manifest.assets).map(([id, a]) => [id, { pack: a.pack, durationMs: a.durationMs, ...(a.narrationKey ? { narrationKey: a.narrationKey } : {}) }])),
  };
}

const read = (file) => JSON.parse(fs.readFileSync(file, 'utf8'));
const text = (value) => `${JSON.stringify(value, null, 2)}\n`;

function outputs() {
  return [
    [path.join(ART_DIR, 'runtime.json'), text(artRuntime(read(path.join(ART_DIR, 'manifest.json')), read(path.join(ART_DIR, 'rights.json'))))],
    [path.join(AUDIO_DIR, 'runtime.json'), text(audioRuntime(read(path.join(AUDIO_DIR, 'manifest.json'))))],
  ];
}

/** Writes both runtime manifests (or, with check, lists the stale ones without writing). */
function generate({ check = false } = {}) {
  const stale = [];
  for (const [file, body] of outputs()) {
    if ((fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null) === body) continue;
    stale.push(path.relative(ROOT, file));
    if (!check) fs.writeFileSync(file, body);
  }
  return stale;
}

module.exports = { artRuntime, audioRuntime, generate };

if (require.main === module) {
  const check = process.argv.includes('--check');
  const stale = generate({ check });
  if (check && stale.length) {
    console.error(`Stale runtime manifests (run node scripts/generate-runtime-manifests.js): ${stale.join(', ')}`);
    process.exit(1);
  }
  console.log(check ? 'Runtime manifests are up to date' : stale.length ? `Wrote ${stale.join(', ')}` : 'Runtime manifests already up to date');
}
